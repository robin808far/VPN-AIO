CREATE TABLE nodes (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    remark TEXT,
    scheme TEXT NOT NULL DEFAULT 'https',
    address TEXT NOT NULL,
    port INTEGER NOT NULL DEFAULT 2053,
    base_path TEXT DEFAULT '/panel',
    api_token TEXT NOT NULL,
    enable BOOLEAN NOT NULL DEFAULT true,
    allow_private_address BOOLEAN NOT NULL DEFAULT false,
    tls_verify_mode TEXT NOT NULL DEFAULT 'verify',
    pinned_cert_sha256 TEXT,
    inbound_sync_mode TEXT NOT NULL DEFAULT 'all',
    inbound_tags TEXT,
    outbound_tag TEXT,
    guid TEXT UNIQUE,
    status TEXT NOT NULL DEFAULT 'unknown',
    last_heartbeat INTEGER NOT NULL DEFAULT 0,
    latency_ms INTEGER,
    xray_version TEXT,
    panel_version TEXT,
    cpu_pct REAL,
    mem_pct REAL,
    uptime_secs INTEGER,
    unavailable_metrics TEXT,
    net_up INTEGER NOT NULL DEFAULT 0,
    net_down INTEGER NOT NULL DEFAULT 0,
    last_error TEXT,
    xray_state TEXT,
    xray_error TEXT,
    config_dirty BOOLEAN NOT NULL DEFAULT false,
    config_dirty_at INTEGER,
    inbounds_adopted_at INTEGER NOT NULL DEFAULT 0,
    down_notified BOOLEAN NOT NULL DEFAULT false,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL
);